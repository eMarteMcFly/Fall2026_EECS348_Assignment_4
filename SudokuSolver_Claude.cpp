/* ============================================================================
 * Class SudokuBoard
 * Source: generated by Claude (Anthropic) via claude.ai.
 *
 * Holds one 9x9 Sudoku grid plus three sets of bitmasks that record which
 * digits are already used in each row, each column, and each 3x3 box.
 * Bit d (1..9) of a mask is set when digit d is present in that unit, so the
 * legal candidates for a cell are found with one OR and one NOT instead of
 * re-scanning 27 cells every time.
 * ============================================================================ */
class SudokuBoard {
public:
    static const int SIZE = 9;                 // the grid is 9 cells wide and tall
    static const int BOX = 3;                  // each block is 3x3 cells
    static const int EMPTY = 0;                // 0 stores a blank square internally
    static const unsigned ALL_DIGITS = 0x3FEu; // bits 1..9 set (binary 11 1111 1110)

    SudokuBoard();                                                      // builds an empty, consistent board
    bool loadFromFile(const std::string& fileName, std::string& error); // reads a puzzle file into the board
    void print(std::ostream& out) const;                                // prints the grid in the input format
    bool isConsistent() const;                                          // false if the givens break a rule
    bool findMostConstrainedEmptyCell(int& row, int& col,
                                      unsigned& candidates) const;      // picks the next cell to branch on
    void place(int row, int col, int digit);                            // writes a digit and marks it used
    void clear(int row, int col);                                       // erases a digit and unmarks it

private:
    static int boxIndex(int row, int col);        // maps (row, col) to its box number 0..8
    static unsigned bitFor(int digit);            // converts a digit 1..9 to its mask bit
    static int countBits(unsigned mask);          // counts how many candidates a mask holds

    std::array<std::array<int, SIZE>, SIZE> cells_; // cells_[r][c] holds 0 (blank) or 1..9
    std::array<unsigned, SIZE> rowUsed_;            // rowUsed_[r] = digits already in row r
    std::array<unsigned, SIZE> colUsed_;            // colUsed_[c] = digits already in column c
    std::array<unsigned, SIZE> boxUsed_;            // boxUsed_[b] = digits already in box b
    bool consistent_;                               // true while no given repeats in a unit
};

/* ---------------------------------------------------------------------------
 * Constructor: start with every cell blank and every mask empty.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
SudokuBoard::SudokuBoard() : consistent_(true) {   // a blank board breaks no rules
    for (int r = 0; r < SIZE; ++r) {               // visit each row
        cells_[r].fill(EMPTY);                     // set every cell in the row to blank
    }
    rowUsed_.fill(0u);                             // no digits used in any row yet
    colUsed_.fill(0u);                             // no digits used in any column yet
    boxUsed_.fill(0u);                             // no digits used in any box yet
}

/* ---------------------------------------------------------------------------
 * loadFromFile: read exactly 81 tokens ('_' or '1'..'9') from fileName.
 * Returns false and fills `error` if the file is missing or malformed.
 * If a given digit repeats in a row/column/box, the board still loads (so it
 * can be printed) but is marked inconsistent, meaning it has no solution.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
bool SudokuBoard::loadFromFile(const std::string& fileName, std::string& error) {
    *this = SudokuBoard();                              // reset to a blank board before loading
    std::ifstream in(fileName.c_str());                 // open the puzzle file for reading
    if (!in) {                                          // the file could not be opened
        error = "could not open file '" + fileName + "'"; // explain the problem to the caller
        return false;                                   // report failure
    }

    std::string token;                                  // holds one whitespace-separated token
    int count = 0;                                      // number of cells read so far (0..81)
    while (in >> token) {                               // read tokens until end of file
        if (count >= SIZE * SIZE) {                     // more than 81 tokens were found
            error = "more than 81 cells in '" + fileName + "'"; // describe the format error
            return false;                               // report failure
        }
        int row = count / SIZE;                         // row of this cell (0..8)
        int col = count % SIZE;                         // column of this cell (0..8)

        if (token == "_") {                             // an underscore marks a blank square
            cells_[row][col] = EMPTY;                   // store it as blank
        } else if (token.size() == 1 && token[0] >= '1' && token[0] <= '9') { // a single digit 1-9
            int digit = token[0] - '0';                 // convert the character to its integer value
            unsigned bit = bitFor(digit);               // mask bit that represents this digit
            int b = boxIndex(row, col);                 // box that contains this cell
            if ((rowUsed_[row] & bit) || (colUsed_[col] & bit) || (boxUsed_[b] & bit)) { // digit repeats
                consistent_ = false;                    // givens break a rule -> unsolvable
            }
            cells_[row][col] = digit;                   // store the given digit
            rowUsed_[row] |= bit;                       // mark the digit as used in its row
            colUsed_[col] |= bit;                       // mark the digit as used in its column
            boxUsed_[b] |= bit;                         // mark the digit as used in its box
        } else {                                        // anything else is not allowed
            error = "invalid token '" + token + "' in '" + fileName + "'"; // describe the bad token
            return false;                               // report failure
        }
        ++count;                                        // one more cell has been read
    }

    if (count != SIZE * SIZE) {                         // fewer than 81 cells were found
        error = "expected 81 cells but found " + std::to_string(count) +
                " in '" + fileName + "'";               // describe the short file
        return false;                                   // report failure
    }
    return true;                                        // the file loaded successfully
}

/* ---------------------------------------------------------------------------
 * print: write the grid using the same layout as the puzzle files
 * (digits separated by spaces, '_' for blanks, one row per line).
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuBoard::print(std::ostream& out) const {
    for (int r = 0; r < SIZE; ++r) {                    // visit each row
        for (int c = 0; c < SIZE; ++c) {                // visit each column in the row
            if (c > 0) {                                // every cell except the first in a row
                out << ' ';                             // gets a space before it
            }
            if (cells_[r][c] == EMPTY) {                // a blank square
                out << '_';                             // is printed as an underscore
            } else {                                    // a filled square
                out << cells_[r][c];                    // is printed as its digit
            }
        }
        out << '\n';                                    // end the row
    }
}

/* ---------------------------------------------------------------------------
 * isConsistent: true when no given digit was duplicated in any unit.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
bool SudokuBoard::isConsistent() const {
    return consistent_;                                 // value recorded while loading
}

/* ---------------------------------------------------------------------------
 * findMostConstrainedEmptyCell: scan the blank cells and choose the one with
 * the FEWEST legal candidates (the "minimum remaining values" rule). Branching
 * on the tightest cell keeps the search tree small.
 *   - Returns false when no blank cell remains (the board is a solution).
 *   - Returns true with candidates == 0 when some blank cell has no legal
 *     digit (a dead end), which tells the solver to backtrack immediately.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
bool SudokuBoard::findMostConstrainedEmptyCell(int& row, int& col,
                                               unsigned& candidates) const {
    bool found = false;                                 // no blank cell seen yet
    int bestCount = SIZE + 1;                           // larger than any real candidate count
    for (int r = 0; r < SIZE; ++r) {                    // visit each row
        for (int c = 0; c < SIZE; ++c) {                // visit each column
            if (cells_[r][c] != EMPTY) {                // skip cells that are already filled
                continue;                               // move on to the next cell
            }
            unsigned used = rowUsed_[r] | colUsed_[c] | boxUsed_[boxIndex(r, c)]; // digits blocked here
            unsigned options = ALL_DIGITS & ~used;      // digits still legal for this cell
            int n = countBits(options);                 // how many legal digits there are
            if (n < bestCount) {                        // this cell is tighter than the best so far
                found = true;                           // remember that a blank cell exists
                bestCount = n;                          // record its candidate count
                row = r;                                // record its row
                col = c;                                // record its column
                candidates = options;                   // record its candidate digits
                if (n <= 1) {                           // 0 = dead end, 1 = forced move
                    return true;                        // nothing can be tighter, stop scanning
                }
            }
        }
    }
    return found;                                       // false means the grid is full
}

/* ---------------------------------------------------------------------------
 * place: put `digit` into (row, col) and mark it used in that row/col/box.
 * The solver only calls this with a digit that is a legal candidate.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuBoard::place(int row, int col, int digit) {
    unsigned bit = bitFor(digit);                       // mask bit for this digit
    cells_[row][col] = digit;                           // write the digit into the grid
    rowUsed_[row] |= bit;                               // the row now contains this digit
    colUsed_[col] |= bit;                               // the column now contains this digit
    boxUsed_[boxIndex(row, col)] |= bit;                // the box now contains this digit
}

/* ---------------------------------------------------------------------------
 * clear: undo a previous place() at (row, col) so the solver can backtrack.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuBoard::clear(int row, int col) {
    unsigned bit = bitFor(cells_[row][col]);            // mask bit of the digit being removed
    cells_[row][col] = EMPTY;                           // blank the cell again
    rowUsed_[row] &= ~bit;                              // the row no longer contains the digit
    colUsed_[col] &= ~bit;                              // the column no longer contains the digit
    boxUsed_[boxIndex(row, col)] &= ~bit;               // the box no longer contains the digit
}

/* ---------------------------------------------------------------------------
 * Small static helpers.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
int SudokuBoard::boxIndex(int row, int col) {
    return (row / BOX) * BOX + (col / BOX);             // boxes numbered 0..8 left-to-right, top-to-bottom
}

unsigned SudokuBoard::bitFor(int digit) {
    return 1u << digit;                                 // digit d lives in bit d of a mask
}

int SudokuBoard::countBits(unsigned mask) {
    int n = 0;                                          // running count of set bits
    while (mask != 0u) {                                // until every set bit is removed
        mask &= mask - 1u;                              // clear the lowest set bit
        ++n;                                            // and count it
    }
    return n;                                           // number of bits that were set
}

/* ============================================================================
 * Class SudokuSolver
 * Source: generated by Claude (Anthropic) via claude.ai.
 *
 * Finds ALL solutions of a puzzle using recursive depth-first search with
 * backtracking, exactly as described in the assignment:
 *   1. pick an empty cell and work out its candidate digits;
 *   2. if there are none, this path is a dead end -> return (backtrack);
 *   3. otherwise try each candidate in turn and recurse with one more cell
 *      filled; undo the move afterwards and try the next candidate;
 *   4. when no empty cell is left (k == 81) the grid is a solution -> save it.
 * Because step 3 keeps going after a success, every solution is found.
 * ============================================================================ */
class SudokuSolver {
public:
    explicit SudokuSolver(const SudokuBoard& puzzle);   // copies the puzzle to solve
    void solve();                                       // runs the full search
    const std::vector<SudokuBoard>& solutions() const;  // every solution found by solve()

private:
    void search();                                      // the recursive backtracking step

    SudokuBoard work_;                                  // board that is filled/unfilled during search
    std::vector<SudokuBoard> solutions_;                // completed grids collected so far
};

/* ---------------------------------------------------------------------------
 * Constructor: keep a private working copy so the caller's puzzle is untouched.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
SudokuSolver::SudokuSolver(const SudokuBoard& puzzle) : work_(puzzle) {} // copy the puzzle

/* ---------------------------------------------------------------------------
 * solve: clear old results, then start the recursion if the givens are legal.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuSolver::solve() {
    solutions_.clear();                                 // forget results from any earlier run
    if (!work_.isConsistent()) {                        // givens already break a Sudoku rule
        return;                                         // so no solution can exist
    }
    search();                                           // begin the depth-first search
}

/* ---------------------------------------------------------------------------
 * search: one level of the recursive depth-first search with backtracking.
 * Recursion depth is at most the number of blank cells (<= 81).
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuSolver::search() {
    int row = 0;                                        // row of the cell to branch on
    int col = 0;                                        // column of the cell to branch on
    unsigned candidates = 0u;                           // legal digits for that cell

    if (!work_.findMostConstrainedEmptyCell(row, col, candidates)) { // no blank cell is left
        solutions_.push_back(work_);                    // the full grid is a solution: save a copy
        return;                                         // go back and look for more solutions
    }

    // If candidates == 0 the loop below runs zero times, so this call simply
    // returns: that is the "no-solution-found" result that triggers backtracking.
    for (int digit = 1; digit <= SudokuBoard::SIZE; ++digit) { // try digits 1..9 in order
        if (candidates & (1u << digit)) {               // only digits that are legal here
            work_.place(row, col, digit);               // make the move
            search();                                   // recurse with one more cell filled
            work_.clear(row, col);                      // undo the move (backtrack)
        }
    }
}

/* ---------------------------------------------------------------------------
 * solutions: read-only access to the grids found by the last solve().
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
const std::vector<SudokuBoard>& SudokuSolver::solutions() const {
    return solutions_;                                  // hand back the stored solutions
}

/* ============================================================================
 * Class SudokuApplication
 * Source: generated by Claude (Anthropic) via claude.ai.
 *
 * Drives the program: for each puzzle file it loads the board, prints the file
 * name and puzzle, runs the solver, and prints every solution (or
 * "No solution found") along with a solution count and the search time.
 * ============================================================================ */
class SudokuApplication {
public:
    explicit SudokuApplication(const std::vector<std::string>& files); // stores the files to process
    int run();                                                         // processes all files

private:
    bool processFile(const std::string& fileName);      // handles a single puzzle file
    static void printDivider(char ch);                  // prints a horizontal separator line

    std::vector<std::string> files_;                    // puzzle file names, in processing order
};

/* ---------------------------------------------------------------------------
 * Constructor: remember which puzzle files to solve.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
SudokuApplication::SudokuApplication(const std::vector<std::string>& files)
    : files_(files) {}                                  // copy the list of file names

/* ---------------------------------------------------------------------------
 * run: process every file; return 0 if all loaded, 1 if any failed to load.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
int SudokuApplication::run() {
    int status = 0;                                     // assume success until a file fails
    for (std::size_t i = 0; i < files_.size(); ++i) {   // visit each file name in order
        if (!processFile(files_[i])) {                  // the file could not be loaded
            status = 1;                                 // remember that something went wrong
        }
    }
    printDivider('=');                                  // closing line after the last puzzle
    return status;                                      // becomes the program's exit code
}

/* ---------------------------------------------------------------------------
 * processFile: load, print, solve, and report one puzzle.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
bool SudokuApplication::processFile(const std::string& fileName) {
    printDivider('=');                                  // separate this puzzle from the previous one
    std::cout << "Puzzle file: " << fileName << '\n';   // required: the puzzle file name

    SudokuBoard puzzle;                                 // board that will hold the file's contents
    std::string error;                                  // receives a message if loading fails
    if (!puzzle.loadFromFile(fileName, error)) {        // try to read the puzzle
        std::cout << "Error: " << error << '\n';        // explain why it could not be read
        return false;                                   // report failure to run()
    }

    std::cout << "\nPuzzle:\n";                         // label for the original puzzle
    puzzle.print(std::cout);                            // required: the puzzle as given in the file

    SudokuSolver solver(puzzle);                        // solver working on a copy of the puzzle
    std::chrono::steady_clock::time_point start =
        std::chrono::steady_clock::now();               // time just before the search starts
    solver.solve();                                     // find every solution
    std::chrono::steady_clock::time_point stop =
        std::chrono::steady_clock::now();               // time just after the search ends
    double ms = std::chrono::duration<double, std::milli>(stop - start).count(); // elapsed milliseconds

    const std::vector<SudokuBoard>& found = solver.solutions(); // results of the search
    if (found.empty()) {                                // the search found nothing
        std::cout << "\nNo solution found\n";           // required message for unsolvable puzzles
    } else {                                            // at least one solution exists
        for (std::size_t i = 0; i < found.size(); ++i) { // print each solution in turn
            std::cout << "\nSolution " << (i + 1) << " of " << found.size() << ":\n"; // numbered label
            found[i].print(std::cout);                  // required: the solved grid
        }
    }

    std::cout << "\nSolutions found: " << found.size()  // total number of solutions
              << "   (search time: " << ms << " ms)\n"; // how long the search took
    return true;                                        // this file was processed successfully
}

/* ---------------------------------------------------------------------------
 * printDivider: print a 50-character line of `ch` to separate sections.
 * Source: Claude (Anthropic).
 * --------------------------------------------------------------------------- */
void SudokuApplication::printDivider(char ch) {
    std::cout << std::string(50, ch) << '\n';           // 50 copies of ch, then a newline
}

